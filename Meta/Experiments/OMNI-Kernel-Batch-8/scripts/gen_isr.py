#!/usr/bin/env python3
"""Generate arch/x86_64/isr.S from the error-code table in src/idt.rs.

Usage: gen_isr.py [--check]   (--check exits 1 if the committed isr.S differs)
The table is read from `has_error_code` so the stubs cannot drift from the Rust side.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
IRQ_VECTORS = 48  # 0..31 exceptions + 16 PIC vectors

HEADER = """/* OMNI Batch 8 interrupt and exception entry stubs. GENERATED by scripts/gen_isr.py from the
 * error-code table in src/idt.rs (checked by scripts/check_asm.py); edit the generator, not this file.
 *
 * Every vector gets its own stub that normalises the stack to
 *     [error code (hardware or dummy 0)] [vector]
 * and jumps to isr_common, which saves the general registers and the SSE state, calls
 * omni8_trap_dispatch(TrapFrame *) and returns with iretq. The TrapFrame layout is
 * src/idt.rs::TrapFrame (176 bytes), asserted by the host tests.
 *
 * Alignment: every gate uses an IST stack whose top is 16-byte aligned; the CPU aligns rsp
 * to 16 before pushing the frame, the frame + stub pushes are 176 bytes (a multiple of 16),
 * and isr_common realigns explicitly for FXSAVE before the call.
 */
    .text
"""

COMMON = """
    .type isr_common, @function
isr_common:
    pushq %rax
    pushq %rcx
    pushq %rdx
    pushq %rbx
    pushq %rbp
    pushq %rsi
    pushq %rdi
    pushq %r8
    pushq %r9
    pushq %r10
    pushq %r11
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    movq %rsp, %rdi
    movq %rsp, %rbx
    subq $512, %rsp
    andq $-16, %rsp
    fxsave (%rsp)
    cld
    call omni8_trap_dispatch
    fxrstor (%rsp)
    movq %rbx, %rsp
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %r11
    popq %r10
    popq %r9
    popq %r8
    popq %rdi
    popq %rsi
    popq %rbp
    popq %rbx
    popq %rdx
    popq %rcx
    popq %rax
    addq $16, %rsp
    iretq
    .size isr_common, .-isr_common

    .section .rodata
    .align 8
    .globl omni8_isr_table
omni8_isr_table:
"""


def error_code_vectors():
    text = (ROOT / "src/idt.rs").read_text()
    m = re.search(r"pub const fn has_error_code\(vector: usize\) -> bool \{\s*matches!\(vector, ([0-9 |]+)\)", text)
    if not m:
        raise SystemExit("cannot find has_error_code in src/idt.rs")
    return {int(x) for x in m.group(1).split("|")}


def generate():
    err = error_code_vectors()
    out = [HEADER]
    for n in range(IRQ_VECTORS):
        out.append(
            f"    .globl omni8_isr_{n}\n    .type omni8_isr_{n}, @function\nomni8_isr_{n}:\n"
            + ("" if n in err else "    pushq $0\n")
            + f"    pushq ${n}\n    jmp isr_common\n    .size omni8_isr_{n}, .-omni8_isr_{n}\n"
        )
    out.append(
        "    .globl omni8_isr_user_test\n    .type omni8_isr_user_test, @function\nomni8_isr_user_test:\n"
        "    pushq $0\n    pushq $0x81\n    jmp isr_common\n    .size omni8_isr_user_test, .-omni8_isr_user_test\n"
    )
    out.append(COMMON)
    for n in range(IRQ_VECTORS):
        out.append(f"    .quad omni8_isr_{n}\n")
    out.append("    .globl omni8_isr_table_end\nomni8_isr_table_end:\n\n    .section .note.GNU-stack, \"\", @progbits\n")
    return "".join(out)


def main():
    target = ROOT / "arch/x86_64/isr.S"
    text = generate()
    if "--check" in sys.argv:
        if target.read_text() != text:
            print("arch/x86_64/isr.S is out of date; run scripts/gen_isr.py")
            return 1
        print("isr.S matches the generator")
        return 0
    target.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
